-- OmniRal

local MapService = {}

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Services
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

local ServerStorage = game:GetService("ServerStorage")
local Workspace = game:GetService("Workspace")

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Modules
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Constants
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

local SPAWN_TEST_MAP = false
local NOISE_SCALE = 10

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Remotes
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Variables
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

local Assets = ServerStorage.Assets
local RNG = Random.new()

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Private Functions
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Public API
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

function MapService.Build()
	local TreeFolder = Assets.Map.Trees.Forest:GetChildren()
	
	local CurrentCF = CFrame.new(-80, 0.05, -80)
	for x = 1, 20 do
		for z = 1, 20 do
			local PlaceHere = CurrentCF
			local Noise = math.noise(PlaceHere.Position.X / NOISE_SCALE, PlaceHere.Position.Z / NOISE_SCALE)
			CurrentCF *= CFrame.new(0, 0, 8)
			if Noise > 0.25 then continue end

			local NewTree = TreeFolder[RNG:NextInteger(1, #TreeFolder)]:Clone()
			NewTree:PivotTo(PlaceHere)
			NewTree.Parent = Workspace

		end
		CurrentCF *= CFrame.new(8, 0, -160)
	end
end

function MapService:Deferred()
	task.delay(3, function()
		if not SPAWN_TEST_MAP then return end
		MapService.Build()
	end)
end

return MapService